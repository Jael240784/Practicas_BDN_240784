CREATE OR REPLACE FUNCTION public.trg_log_row() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE op TEXT; detail TEXT;
BEGIN
  op := CASE WHEN TG_OP='INSERT' THEN 'Create' WHEN TG_OP='UPDATE' THEN 'Update' ELSE 'Delete' END;
  IF TG_TABLE_NAME='tb_users' THEN
    IF TG_OP='DELETE' THEN
      detail := format('Usuario eliminado. ID=%s, email=%s, nick=%s',OLD.id,OLD.email,OLD.nick);
    ELSIF TG_OP='INSERT' THEN
      detail := format('Usuario creado. ID=%s, email=%s, nick=%s',NEW.id,NEW.email,NEW.nick);
    ELSE
      detail := format('Usuario actualizado. ID=%s, email=%s, nick=%s',NEW.id,NEW.email,NEW.nick);
    END IF;
  ELSE
    IF TG_OP='DELETE' THEN
      detail := format('Producto eliminado. ID=%s, SKU=%s, nombre=%s',OLD.id,OLD.sku,OLD.name);
    ELSIF TG_OP='INSERT' THEN
      detail := format('Producto creado. ID=%s, SKU=%s, nombre=%s',NEW.id,NEW.sku,NEW.name);
    ELSE
      detail := format('Producto actualizado. ID=%s, SKU=%s, nombre=%s',NEW.id,NEW.sku,NEW.name);
    END IF;
  END IF;
  INSERT INTO public.tb_logs(table_name,table_operation,db_user,operation_description)
  VALUES(TG_TABLE_NAME,op,session_user,detail);
  IF TG_OP='DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS trg_users_log ON public.tb_users;
CREATE TRIGGER trg_users_log AFTER INSERT OR UPDATE OR DELETE ON public.tb_users
FOR EACH ROW EXECUTE FUNCTION public.trg_log_row();
DROP TRIGGER IF EXISTS trg_products_log ON public.tb_products;
CREATE TRIGGER trg_products_log AFTER INSERT OR UPDATE OR DELETE ON public.tb_products
FOR EACH ROW EXECUTE FUNCTION public.trg_log_row();

CREATE OR REPLACE VIEW public.vw_trazabilidad_usuarios AS
SELECT u.nick,u.email,l.db_user AS inserted_by,
       COALESCE(NULLIF(CONCAT_WS(', ',nr.native_roles,app.rol),''),'Sin rol') AS roles,
       l.operation_description,l.operation_date
FROM public.tb_users u
JOIN public.tb_logs l ON l.operation_description LIKE '%'||'email='||u.email||'%'
                     AND l.operation_description LIKE '%'||'nick='||u.nick||'%'
LEFT JOIN public.usuarios app ON app.usuario=split_part(l.db_user,'@',1)
LEFT JOIN LATERAL (
  SELECT string_agg(r.rolname,', ' ORDER BY r.rolname) AS native_roles
  FROM pg_auth_members m
  JOIN pg_roles r ON r.oid=m.roleid
  JOIN pg_roles member ON member.oid=m.member
  WHERE member.rolname=split_part(l.db_user,'@',1)
) nr ON TRUE
WHERE l.table_name='tb_users' AND l.table_operation='Create';
CREATE OR REPLACE VIEW public.vw_trazabilidad_productos AS
SELECT p.id,p.name,p.description,l.db_user AS inserted_by,
       COALESCE(NULLIF(CONCAT_WS(', ',nr.native_roles,app.rol),''),'Sin rol') AS roles,
       l.operation_description,l.operation_date
FROM public.tb_products p
JOIN public.tb_logs l ON l.operation_description LIKE '%'||'ID='||p.id||',%'
LEFT JOIN public.usuarios app ON app.usuario=split_part(l.db_user,'@',1)
LEFT JOIN LATERAL (
  SELECT string_agg(r.rolname,', ' ORDER BY r.rolname) AS native_roles
  FROM pg_auth_members m
  JOIN pg_roles r ON r.oid=m.roleid
  JOIN pg_roles member ON member.oid=m.member
  WHERE member.rolname=split_part(l.db_user,'@',1)
) nr ON TRUE
WHERE l.table_name='tb_products' AND l.table_operation='Create';
CREATE OR REPLACE VIEW public.vw_total_products_by_category AS
SELECT c.id AS category_id,c.name AS category_name,COUNT(pc.product_id) AS total_products
FROM public.tbc_categories c
LEFT JOIN public.tbd_products_categories pc ON pc.category_id=c.id
GROUP BY c.id,c.name;

